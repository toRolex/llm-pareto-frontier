import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {createMotion,retargetMotion,sampleMotion,createCameraPlan,sampleCameraPlan} from './motion.mjs';
const html=readFileSync(new URL('../prototype-4d-3d.html',import.meta.url),'utf8');
const runtime=html.match(/\/\/ MOTION_RUNTIME\n([\s\S]*?)\/\/ END_MOTION_RUNTIME/)[1];
assert.equal(runtime,readFileSync(new URL('./motion.mjs',import.meta.url),'utf8').replace(/^export /gm,''));
const inline=vm.runInNewContext(`${runtime}\n({createMotion,retargetMotion,sampleMotion,createCameraPlan,sampleCameraPlan})`);
for(const api of [{createMotion,retargetMotion,sampleMotion,createCameraPlan,sampleCameraPlan},inline]) {
  let now=0;
  const targets=new Map([['shared',[10,0,0]],['new',[5,0,0]]]);
  const current=new Map([['shared',{position:[0,0,0],alpha:1}],['old',{position:[2,0,0],alpha:1}]]);
  const motion=api.createMotion('B',targets,current,now);
  assert.equal(motion.duration,240);
  now=60;
  const before=api.sampleMotion(motion,now);
  assert.equal(before.points.get('shared').position[0],0.625);
  assert.equal(before.points.get('old').alpha,0.9375);
  assert.equal(before.points.get('new').alpha,0.0625);
  assert.equal(before.swap,false);
  assert.equal(before.topologyAlpha,0.5);
  assert.equal(api.retargetMotion(motion,'B',targets,now),motion,'same target retains clock and object');
  const next=api.retargetMotion(motion,'C',new Map([['shared',[20,0,0]],['old',[3,0,0]]]),now,{shownAlpha:before.topologyAlpha});
  const interrupted=api.sampleMotion(next,now);
  for(const id of ['shared','old','new']) {
    assert.equal(JSON.stringify(interrupted.points.get(id)),JSON.stringify(before.points.get(id)),'interrupt preserves actual position and presence');
  }
  assert.equal(interrupted.topologyAlpha,0.5);
  const zero=api.sampleMotion(motion,120);
  assert.equal(zero.swap,true);
  assert.equal(zero.topologyAlpha,0,'topology replaced only at zero');
  assert.equal(api.sampleMotion(motion,180).topologyAlpha,0.5);
  assert.equal(api.sampleMotion(motion,240).points.get('old').alpha,0);
  assert.equal(api.sampleMotion(motion,240).done,true);
  assert.equal(motion.keyed.size,3,'one shared key, not two overlapping shared dots');
  const reduced=api.createMotion('R',targets,current,now,{reduced:true});
  const final=api.sampleMotion(reduced,now);
  assert.equal(final.done,true);
  assert.equal(final.topologyAlpha,1);
  assert.equal(final.points.get('shared').position[0],10);
  assert.equal(final.points.get('old').alpha,0);
  const from={position:[0,0,10],target:[0,0,0],fov:45},to={position:[10,0,0],target:[2,0,0],fov:30};
  const camera=api.createCameraPlan('cost',from,to,0);
  const pose=api.sampleCameraPlan(camera,60);
  assert.equal(pose.position[0],0.625);
  const retarget=api.createCameraPlan('tok',pose,from,60);
  assert.equal(JSON.stringify(api.sampleCameraPlan(retarget,60).position),JSON.stringify(pose.position));
  assert.equal(api.sampleCameraPlan(retarget,60).fov,pose.fov);
  assert.equal(api.sampleCameraPlan(camera,240).position[0],10,'data retarget never mutates camera destination');
  assert.equal(api.sampleMotion(next,300).points.get('shared').position[0],20,'data continues independently of camera ownership');
}
const script=html.split('<script>').at(-1).split('</script>')[0];
const sampler=script.slice(script.indexOf('function sampleDataMotion(now)'),script.indexOf('function displayedPoint(m)'));
const vec=()=>({value:[0,0,0],fromArray(v){this.value=v.slice();},copy(v){this.value=v.value.slice();}});
const nodes=()=>[{position:vec(),userData:{model:{id:'old'}},material:{opacity:1},visible:true}];
const outgoing={nodes:nodes(),position:vec()};
const shared={nodes:nodes(),position:vec()};
const removed=[],retired=[],state={dataset:{}};
const group={traverse(){},remove(o){removed.push(o);}};
const shown={userData:{alpha:1},children:[],traverse(){}};
const incoming={userData:{},children:[],traverse(){}};
const world={handles:new Map([['old',outgoing],['shared',shared]]),rows:[{id:'shared'}],group,topology:incoming,helperGroup:{}};
const Motion=createMotion('end',new Map([['shared',[10,0,0]]]),new Map([['old',{position:[2,0,0],alpha:1}],['shared',{position:[0,0,0],alpha:1}]]),0);
const context={Motion,world,shownTopology:shown,retirements:retired,sampleMotion,hoverState:null,S:{view:'cost'},scene:{remove(o){assert.equal(o.userData.alpha,0,'actual adapter hides old topology before detaching');}},document:{getElementById(){return state;}},THREE:{Group:class{add(){}}}};
vm.createContext(context);
vm.runInContext(sampler+'\nsampleDataMotion(60)',context);
assert.equal(world.handles.size,2);
assert.equal(outgoing.nodes[0].material.opacity,0.9375);
vm.runInContext('sampleDataMotion(120)',context);
assert.equal(context.shownTopology,incoming);
assert.equal(retired[0],shown);
assert.equal(incoming.userData.alpha,0);
vm.runInContext('sampleDataMotion(240)',context);
assert.equal(world.handles.has('old'),false,'actual adapter retires outgoing observation');
assert.equal(world.handles.has('shared'),true);
assert.equal(removed.length,1);
assert.equal(retired.length,2,'topology and outgoing handle queued for frame-boundary disposal');
assert.equal(shared.position.value[0],10);
new vm.Script(script);
console.log('PASS motion fake-clock behavior, interruption, presence, zero-alpha topology swap, reduced motion, camera independence, inline parity and syntax');
